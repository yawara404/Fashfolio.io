// Japanese particles and copula endings are ignored instead of being reported
// as untranslated words.
const IGNORED_JAPANESE = new Set([
  "の",
  "を",
  "に",
  "が",
  "は",
  "も",
  "と",
  "で",
  "や",
  "へ",
  "から",
  "まで",
  "より",
  "な",
  "い",
  "く",
  "て",
  "た",
  "だ",
  "です",
  "ます",
  "した",
  "する",
  "っぽい",
  "風",
  "系",
  "柄",
]);

const ENTRIES = Object.entries(DICTIONARY)
  .map(([ja, en]) => [ja.normalize("NFKC").toLowerCase(), en] as const)
  .sort((a, b) => b[0].length - a[0].length);

export interface JaEnTranslation {
  tokens: string[];
  text: string;
  untranslated: string[];
}

const isJapanese = (char: string) =>
  /[\u3040-\u30ff\u3400-\u9fff\uff66-\uff9f]/.test(char);
const isEnglishWord = (char: string) => /[a-z0-9'\-]/i.test(char);
const isSeparator = (char: string) => /[\s,、。.・/／|｜:：;；()（）「」『』【】]/.test(char);

function pushEnglishTokens(target: string[], value: string) {
  for (const part of value.split(/[,、。・/／|｜()（）「」『』【】]+/)) {
    const token = part.trim();
    if (token) target.push(token);
  }
}

function uniqueTokens(tokens: string[]) {
  const seen = new Set<string>();
  return tokens.filter((token) => {
    const key = token.toLowerCase();
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

/**
 * Convert Japanese coordinate words such as
 * 「春のカフェのガーリーコーデ」 into `spring, cafe, girly, coordinate`.
 */
export function translateJaToEnPrompt(input: string): JaEnTranslation {
  const text = input.normalize("NFKC").toLowerCase();
  const tokens: string[] = [];
  const untranslated: string[] = [];
  let english = "";
  let unknown = "";

  const flushEnglish = () => {
    if (english.trim()) pushEnglishTokens(tokens, english);
    english = "";
  };
  const flushUnknown = () => {
    const value = unknown
      .trim()
      .replace(/^[のをにがはもとでやへ]+/, "")
      .replace(/[のをにがはもとでやへ]+$/, "");
    const meaningful = /[\u3400-\u9fff\u30a0-\u30ff]/.test(value);
    if ((value.length > 1 || meaningful) && !IGNORED_JAPANESE.has(value)) untranslated.push(value);
    unknown = "";
  };

  let index = 0;
  while (index < text.length) {
    const match = ENTRIES.find(([ja]) => ja && text.startsWith(ja, index));
    if (match) {
      flushEnglish();
      flushUnknown();
      tokens.push(match[1]);
      index += match[0].length;
      continue;
    }

    const char = text[index]!;
    if (isJapanese(char)) {
      flushEnglish();
      unknown += char;
      index += 1;
      continue;
    }
    if (isEnglishWord(char) || char === " " || char === "-" || char === "'") {
      flushUnknown();
      english += char;
      index += 1;
      continue;
    }

    // Punctuation acts as a token boundary.
    if (isSeparator(char) || char === ",") {
      flushEnglish();
      flushUnknown();
    }
    index += 1;
  }
  flushEnglish();
  flushUnknown();

  const result = uniqueTokens(tokens);
  return {
    tokens: result,
    text: result.join(", "),
    untranslated: [...new Set(untranslated)],
  };
}
